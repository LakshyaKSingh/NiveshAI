"""
Predictions, Signals, and Model Metadata Endpoints
===================================================
"""

import json
from typing import List, Optional
from fastapi import APIRouter, Depends, Query, HTTPException
from sqlalchemy.orm import Session
from sqlalchemy import desc

from tradepilot.api.schemas.prediction import (
    PredictionItem,
    LatestPredictionsResponse,
    SignalItem,
    SignalsResponse,
    RunInferenceRequest,
    ActiveModelResponse,
)
from tradepilot.api.dependencies import get_db, require_role
from tradepilot.db.models import PredictionRecord, SignalRecord, User
from tradepilot.execution.agent import TradingAgent
from tradepilot.api.config import settings

router = APIRouter(prefix="/api/v1", tags=["Predictions & Strategy"])

# Singleton agent instance for on-demand inference
_agent_instance = None


def get_agent() -> TradingAgent:
    global _agent_instance
    if _agent_instance is None:
        _agent_instance = TradingAgent()
    return _agent_instance


@router.get("/predictions/latest", response_model=LatestPredictionsResponse)
def get_latest_predictions(
    limit: int = Query(default=20, ge=1, le=100),
    symbol: Optional[str] = Query(default=None),
    db: Session = Depends(get_db),
):
    """Fetch latest class probability predictions generated by the ML model."""
    query = db.query(PredictionRecord)
    if symbol:
        query = query.filter(PredictionRecord.symbol == symbol.upper())
    records = query.order_by(desc(PredictionRecord.timestamp)).limit(limit).all()

    items = [
        PredictionItem(
            id=r.id,
            cycle_id=r.cycle_id,
            symbol=r.symbol,
            prob_up=r.prob_up,
            prob_neutral=r.prob_neutral,
            prob_down=r.prob_down,
            predicted_class=r.predicted_class,
            model_version=r.model_version,
            timestamp=r.timestamp,
        )
        for r in records
    ]
    return LatestPredictionsResponse(total=len(items), predictions=items)


@router.post("/predictions/run", response_model=LatestPredictionsResponse)
def run_manual_inference(
    req: Optional[RunInferenceRequest] = None,
    current_user: User = Depends(require_role(["trader", "admin"])),
    db: Session = Depends(get_db),
):
    """Trigger an immediate inference and signal evaluation cycle."""
    agent = get_agent()
    target_syms = req.symbols if req else None
    cycle = agent.run_cycle(db, target_symbols=target_syms)

    # Return predictions from this cycle
    records = (
        db.query(PredictionRecord)
        .filter(PredictionRecord.cycle_id == cycle.id)
        .all()
    )
    items = [
        PredictionItem(
            id=r.id,
            cycle_id=r.cycle_id,
            symbol=r.symbol,
            prob_up=r.prob_up,
            prob_neutral=r.prob_neutral,
            prob_down=r.prob_down,
            predicted_class=r.predicted_class,
            model_version=r.model_version,
            timestamp=r.timestamp,
        )
        for r in records
    ]
    return LatestPredictionsResponse(total=len(items), predictions=items)


@router.get("/signals", response_model=SignalsResponse)
def get_latest_signals(
    limit: int = Query(default=20, ge=1, le=100),
    symbol: Optional[str] = Query(default=None),
    db: Session = Depends(get_db),
):
    """Retrieve strategy signals (BUY, EXIT, HOLD) with rule reasoning."""
    query = db.query(SignalRecord)
    if symbol:
        query = query.filter(SignalRecord.symbol == symbol.upper())
    records = query.order_by(desc(SignalRecord.timestamp)).limit(limit).all()

    items = [
        SignalItem(
            id=r.id,
            cycle_id=r.cycle_id,
            symbol=r.symbol,
            signal=r.signal,
            reasoning=r.reasoning,
            threshold=r.threshold,
            timestamp=r.timestamp,
        )
        for r in records
    ]
    return SignalsResponse(total=len(items), signals=items)


@router.get("/models/active", response_model=ActiveModelResponse)
def get_active_model_metadata():
    """Inspect active trained model artifact version, feature list, and evaluation metrics."""
    if not settings.MODEL_METADATA_PATH.exists():
        raise HTTPException(status_code=404, detail="Model metadata not found.")

    with open(settings.MODEL_METADATA_PATH, "r", encoding="utf-8") as f:
        meta = json.load(f)

    return ActiveModelResponse(
        model_version=meta.get("algorithm", "RandomForest_v1"),
        algorithm=meta.get("algorithm", "RandomForestClassifier"),
        num_features=len(meta.get("features", [])),
        feature_names=meta.get("features", []),
        classes=meta.get("classes", ["DOWN", "NEUTRAL", "UP"]),
        metrics=meta.get("test_metrics", {}),
        artifact_path=str(settings.MODEL_PATH.name),
        trained_at=meta.get("trained_at", None),
    )
