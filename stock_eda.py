# --- 3. Chronological Time-Series Train/Val/Test Split ---
# Prevent 5-day horizon overlap leakage by removing 5 trading days at the boundary of splits per stock.
def chronological_split_with_safety(df, train_end_year=2023, val_end_year=2024, safety_days=5):
    df_sorted = df.sort_values(by=['symbol', 'timestamp']).reset_index(drop=True)

    # Generate aligned boolean masks
    train_mask = df_sorted['timestamp'].dt.year <= train_end_year
    val_mask = (df_sorted['timestamp'].dt.year > train_end_year) & (df_sorted['timestamp'].dt.year <= val_end_year)
    test_mask = df_sorted['timestamp'].dt.year > val_end_year

    train_indices = []
    val_indices = []
    test_indices = []

    for sym, group in df_sorted.groupby('symbol'):
        # Locate positional indexes aligned with our masks to avoid reindexing warning
        g_train = group.loc[train_mask[group.index]]
        g_val = group.loc[val_mask[group.index]]
        g_test = group.loc[test_mask[group.index]]

        # Purge boundary rows
        if len(g_train) > safety_days:
            g_train_clean = g_train.iloc[:-safety_days]
        else:
            g_train_clean = g_train

        if len(g_val) > safety_days:
            g_val_clean = g_val.iloc[:-safety_days]
        else:
            g_val_clean = g_val

        train_indices.extend(g_train_clean.index)
        val_indices.extend(g_val_clean.index)
        test_indices.extend(g_test.index)

    return df_sorted.loc[train_indices], df_sorted.loc[val_indices], df_sorted.loc[test_indices]

